/** 시/도 목록. 행사가 몰리는 수도권을 위로 올린다. */
export const REGION_ORDER: readonly string[] = Object.keys(REGION_DISTRICTS);

export const REGION_OPTIONS: SelectOption[] = REGION_ORDER.map((region) => ({
  label: region,
  value: region,
}));

export const REGION_FILTER_OPTIONS: SelectOption[] = [
  { label: "전체 지역", value: "" },
  ...REGION_OPTIONS,
];

/** 시/도에 속한 시·군·구 선택지. 시/도를 아직 안 골랐으면 빈 목록이다. */
export const districtOptions = (region: string): SelectOption[] =>
  (REGION_DISTRICTS[region] ?? []).map((district) => ({
    label: district,
    value: district,
  }));

/**
 * 자유 입력으로 저장돼 있던 예전 값을 시/도 + 구로 나눈다.
 *
 * "서울 강남", "인천 남동구"처럼 적혀 있던 기존 데이터를 새 구조로 옮길 때 쓴다.
 * 못 알아보는 값은 시/도만 채우고 구는 비워 둬서, 수정 화면에서 사람이 고르게 한다.
 */
export const splitLegacyRegion = (
  value: string,
): { region: string; district: string } => {
  const trimmed = (value ?? "").trim();

  if (!trimmed) return { region: "", district: "" };

  const region = REGION_ORDER.find((item) => trimmed.startsWith(item));

  if (!region) return { region: "", district: "" };

  const rest = trimmed.slice(region.length).trim();
  const districts = REGION_DISTRICTS[region];
  const district =
    districts.find((item) => item === rest) ??
    // "강남"처럼 접미사가 빠진 값도 살려 준다.
    districts.find((item) => item.startsWith(rest) && rest.length > 0) ??
    "";

  return { region, district };
};
